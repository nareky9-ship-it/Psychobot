"""
Простой детектор кризисных сообщений (риск суицида/самоповреждения).

ВАЖНО: это НЕ надёжная система клинической оценки риска, а базовый
"предохранитель" по ключевым словам/фразам. Его задача - в дополнение
к ответу модели гарантированно показать горячие линии, даже если
языковая модель этого не сделает сама или ответит неудачно.

Детектор специально консервативный (лучше сработать лишний раз,
чем пропустить реальный кризис).
"""

import re

# Ключевые фразы на трёх языках. Список не претендует на полноту,
# но покрывает наиболее частые прямые формулировки.
_CRISIS_PATTERNS = [
    # English
    r"\bkill myself\b",
    r"\bwant to die\b",
    r"\bend my life\b",
    r"\bsuicid\w*\b",
    r"\bself[\s-]?harm\b",
    r"\bcut myself\b",
    r"\bno reason to live\b",
    r"\bbetter off dead\b",

    # Russian
    r"покончить с собой",
    r"хочу умереть",
    r"не хочу жить",
    r"суицид\w*",
    r"самоубийств\w*",
    r"порезать себя",
    r"порезал(а)? себя",
    r"нет смысла жить",
    r"лучше бы я умер",

    # Armenian
    r"ինքնասպան\w*",
    r"ուզում եմ մեռնել",
    r"կյանքս ավարտել",
    r"ուզում եմ վերջ տալ",
    r"ապրելու իմաստ չկա",
]

_COMPILED_PATTERNS = [re.compile(p, re.IGNORECASE | re.UNICODE) for p in _CRISIS_PATTERNS]


def contains_crisis_language(text: str) -> bool:
    """Возвращает True, если сообщение содержит фразы, указывающие на
    возможный кризис/риск суицида или самоповреждения."""
    if not text:
        return False

    for pattern in _COMPILED_PATTERNS:
        if pattern.search(text):
            return True
    return False
